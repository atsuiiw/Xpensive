#!/usr/bin/env node
/**
 * Generates src/config/api.js from the API_URI environment variable.
 *
 * CRA/webpack only inlines REACT_APP_-prefixed vars into the client bundle,
 * so a custom-named var like API_URI cannot be read directly at runtime.
 * This script resolves API_URI at build/test time and writes it into a module
 * that the bundler can import.
 *
 * Resolution order:
 *   1. process.env.API_URI (set explicitly on the command line / by the host)
 *   2. the dotenv file for the current mode (.env.production for NODE_ENV=production,
 *      otherwise .env)
 *
 * Writes <frontend>/src/config/api.js exporting { API_URI }. The file is
 * gitignored and regenerated on every start/build.
 */
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import dotenv from 'dotenv';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function loadDotEnv(mode) {
  const file = mode === 'production' ? '.env.production' : '.env';
  const path = join(root, file);
  if (existsSync(path)) {
    dotenv.config({ path });
  }
}

const nodeEnv = process.env.NODE_ENV || 'development';
loadDotEnv(nodeEnv);

// process.env.API_URI may have been populated by dotenv.config() above or by
// an explicit environment variable set by the host/CLI. Prefer an explicit
// env var that pre-existed the dotenv load.
const apiUri = (process.env.API_URI || '').trim().replace(/\/+$/, '');

const outDir = join(root, 'src', 'config');
const outFile = join(outDir, 'api.js');
mkdirSync(outDir, { recursive: true });

const source = `// AUTO-GENERATED by scripts/gen-api-config.mjs. Do not edit.
// Contains the resolved API base URL for the current build.
export const API_URI = ${JSON.stringify(apiUri)};
`;

writeFileSync(outFile, source);
console.log(`gen-api-config: wrote ${outFile} (API_URI=${apiUri || '<empty>'} mode=${nodeEnv})`);
